"""Kaggle kernel that scores retrieval candidates with several cross-encoders on the GPU.

Generated by scripts/kaggle/rerank.py, which fills in the constants below. Reranking the
candidates of all benchmark questions takes hours on a laptop CPU and minutes on a GPU, so the
comparison between rerankers runs here. The kernel reads the candidates from a private Kaggle
dataset and writes one scores file per model, which `evaluation.cli report` consumes.
"""

import base64
import hashlib
import json
import subprocess
import sys
import time
import traceback
from pathlib import Path

WHEEL_NAME = "__WHEEL_NAME__"
WHEEL_SHA256 = "__WHEEL_SHA256__"
WHEEL_B64 = """__WHEEL_B64__"""
JOB = json.loads("""__JOB__""")

INPUT = Path("/kaggle/input")  # attached datasets are mounted below this folder
WORK = Path("/kaggle/working")
SCRATCH = Path("/tmp/rag")


def run(*command: str) -> None:
    print("+", " ".join(command), flush=True)
    subprocess.run(command, check=True)


def install_code() -> None:
    wheel_bytes = base64.b64decode(WHEEL_B64)
    if hashlib.sha256(wheel_bytes).hexdigest() != WHEEL_SHA256:
        raise SystemExit("the embedded wheel is corrupt")
    wheel = SCRATCH / WHEEL_NAME
    wheel.write_bytes(wheel_bytes)
    # Dependencies come from the Kaggle image; Python may be older than the wheel declares.
    run(
        sys.executable, "-m", "pip", "install", "-q", "--no-deps", "--ignore-requires-python",
        str(wheel),
    )  # fmt: skip
    try:
        import pyarrow  # noqa: F401
        import sentence_transformers  # noqa: F401
    except ImportError:
        run(sys.executable, "-m", "pip", "install", "-q", "pyarrow", "sentence-transformers")


def find(name: str) -> Path:
    matches = sorted(INPUT.rglob(name))
    if not matches:
        raise SystemExit(f"{name} is not in the attached dataset; found {sorted(INPUT.rglob('*'))}")
    return matches[0]


def main() -> None:
    started = time.time()
    SCRATCH.mkdir(parents=True, exist_ok=True)
    install_code()
    import torch

    device = "cuda" if torch.cuda.is_available() else "cpu"
    print("torch", torch.__version__, "device", device, flush=True)
    if device == "cpu":
        raise SystemExit("no GPU is available: refusing to score on the CPU")
    candidates, questions = find("candidates.dat"), find("questions.parquet")

    finished, failed = [], []
    for model in JOB["models"]:
        tag = model.replace("/", "_")
        out = WORK / f"rerank-{tag}.jsonl.gz"
        try:
            run(
                sys.executable, "-m", "rag_engine.evaluation.cli", "rerank",
                "--questions", str(questions), "--candidates", str(candidates),
                "--model", model, "--out", str(out), "--pool", str(JOB["pool"]),
                "--device", device, "--batch-size", str(JOB["batch_size"]),
            )  # fmt: skip
            finished.append(model)
        except subprocess.CalledProcessError:
            traceback.print_exc()
            failed.append(model)
    (WORK / "job.json").write_text(
        json.dumps(
            {
                "job": JOB,
                "finished": finished,
                "failed": failed,
                "seconds": round(time.time() - started),
            },
            indent=2,
        )
    )
    print(f"done: {len(finished)} models scored, {len(failed)} failed", flush=True)
    if not finished:
        raise SystemExit("no model could be scored")


if __name__ == "__main__":
    try:
        main()
    except Exception:
        traceback.print_exc()
        sys.exit(1)
