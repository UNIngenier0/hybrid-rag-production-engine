"""Kaggle kernel that embeds the corpus on the GPU.

Generated by scripts/kaggle/orchestrate.py, which fills in the three constants below. The wheel
holds this repository's code at the commit being run, so the notebook chunks documents exactly
like the local pipeline and the vector shards it produces are accepted by `load-vectors`.
"""

import base64
import hashlib
import json
import subprocess
import sys
import time
import traceback
from pathlib import Path

WHEEL_NAME = "__WHEEL_NAME__"
WHEEL_SHA256 = "__WHEEL_SHA256__"
WHEEL_B64 = """__WHEEL_B64__"""
JOB = json.loads("""__JOB__""")

WORK = Path("/kaggle/working")
SCRATCH = Path("/tmp/rag")  # the 1.4 GB corpus stays out of the kernel's saved output


def run(*command: str) -> None:
    print("+", " ".join(command), flush=True)
    subprocess.run(command, check=True)


def install_code() -> None:
    wheel_bytes = base64.b64decode(WHEEL_B64)
    if hashlib.sha256(wheel_bytes).hexdigest() != WHEEL_SHA256:
        raise SystemExit("the embedded wheel is corrupt")
    wheel = SCRATCH / WHEEL_NAME
    wheel.write_bytes(wheel_bytes)
    # Dependencies come from the Kaggle image; Python may be older than the wheel declares.
    run(
        sys.executable,
        "-m",
        "pip",
        "install",
        "-q",
        "--no-deps",
        "--ignore-requires-python",
        str(wheel),
    )
    try:
        import pyarrow  # noqa: F401
        import sentence_transformers  # noqa: F401
    except ImportError:
        run(sys.executable, "-m", "pip", "install", "-q", "pyarrow", "sentence-transformers")


def require_gpu() -> list[str]:
    import torch

    print("torch", torch.__version__, "cuda", torch.version.cuda, flush=True)
    names = [torch.cuda.get_device_name(i) for i in range(torch.cuda.device_count())]
    if not names and not JOB.get("cpu_workers"):
        raise SystemExit("no GPU is available: refusing to embed on the CPU")
    print("GPUs:", names, flush=True)
    return names


def main() -> None:
    started = time.time()
    SCRATCH.mkdir(parents=True, exist_ok=True)
    install_code()
    gpus = require_gpu()
    run(
        sys.executable,
        "-m",
        "rag_engine.ingestion.download",
        "--dest",
        str(SCRATCH / "raw"),
        "documents",
    )

    command = [
        sys.executable, "-m", "rag_engine.workers.embed_corpus",
        "--parquet", str(SCRATCH / "raw" / "documents" / "test.parquet"),
        "--out", str(WORK / "vectors"),
        "--docs-per-shard", str(JOB["docs_per_shard"]),
        "--first-shard", str(JOB["first_shard"]),
        "--batch-size", str(JOB["batch_size"]),
    ]  # fmt: skip
    if not gpus:  # only reachable when the job allows CPU workers, which is for tests
        command += ["--device", ",".join(["cpu"] * int(JOB["cpu_workers"]))]
    if JOB.get("last_shard") is not None:
        command += ["--last-shard", str(JOB["last_shard"])]
    if JOB.get("limit_docs") is not None:
        command += ["--limit-docs", str(JOB["limit_docs"])]
    run(*command)

    outputs = sorted((WORK / "vectors").iterdir())
    total = sum(path.stat().st_size for path in outputs)
    (WORK / "job.json").write_text(
        json.dumps(
            {
                "job": JOB,
                "gpus": gpus,
                "seconds": round(time.time() - started),
                "output_bytes": total,
            },
            indent=2,
        )
    )
    print(
        f"done: {len(outputs)} files, {total / 1e9:.2f} GB in {time.time() - started:.0f}s",
        flush=True,
    )


if __name__ == "__main__":
    try:
        main()
    except Exception:
        traceback.print_exc()
        sys.exit(1)
